"""Minecraft resource-pack tools — put a texture where the game will actually find it.

Four tools over the domain logic in ``core/minecraft.py``:

  * ``write_pack_mcmeta`` — make a directory a loadable resource pack.
  * ``export_minecraft_texture`` — export a sprite to
    ``<pack>/assets/<ns>/textures/<category>/<name>.png``, as a vertical frame strip plus
    a ``.png.mcmeta`` sidecar when the sprite is animated.
  * ``write_texture_mcmeta`` — write or repair that sidecar on its own.
  * ``validate_minecraft_texture`` — check size, power-of-two, frame count, sidecar
    presence and tiling seams before the pack ships.

Every failure these catch is one the game reports badly or not at all: a missing sidecar
shows as squashed art, a non-power-of-two size as broken mipmaps, a tiling seam as a grid
of lines across a wall that looked fine in the editor.
"""

from __future__ import annotations

import json
from pathlib import Path

from ..app import mcp
from ..core import minecraft as mc
from ..core.errors import ExportError
from ..core.manifest import file_entry, sprite_summary, workflow_manifest
from ..core.paths import ensure_output_path
from . import export, inspect

# get_pixels caps a single read at 4096 pixels, so wide textures are read in horizontal
# bands and stitched. Reading only the edges would be cheaper but would leave nothing to
# compare a wrap transition against — the seam check is a comparison, not a measurement.
_PIXELS_PER_READ = 4096


# --------------------------------------------------------------------------- #
# Pack scaffolding                                                            #
# --------------------------------------------------------------------------- #
@mcp.tool()
def write_pack_mcmeta(
    pack_root: str,
    mc_version: str | None = None,
    pack_format: int | None = None,
    description: str = "Generated by aseprite-mcp",
    supported_min: int | None = None,
    supported_max: int | None = None,
    overwrite: bool = False,
) -> dict:
    """Write ``<pack_root>/pack.mcmeta`` — the file that makes a directory a resource pack.

    Args:
        pack_root: Directory to become the pack root (created if needed).
        mc_version: A known Minecraft version (e.g. "1.21.1") to look the format up from.
            Defaults to 1.21.1.
        pack_format: The format number, overriding `mc_version`. Required for versions
            outside the known table — an unverified guess produces a pack the game
            rejects as incompatible, so it is refused rather than guessed.
        supported_min, supported_max: Optional inclusive `supported_formats` range,
            letting one pack load across several game versions.

    Returns a ``workflow_manifest.v1`` manifest (kind ``minecraft_pack``).
    """
    resolved_format = mc.resolve_pack_format(mc_version, pack_format)
    supported = None
    if supported_min is not None or supported_max is not None:
        if supported_min is None or supported_max is None:
            raise ExportError("supported_min and supported_max must be given together.")
        if supported_min > supported_max:
            raise ExportError(
                f"supported_min ({supported_min}) is greater than supported_max "
                f"({supported_max})."
            )
        supported = {"min_inclusive": supported_min, "max_inclusive": supported_max}

    document = mc.pack_mcmeta(resolved_format, description, supported)
    out = ensure_output_path(f"{pack_root}/pack.mcmeta", overwrite=overwrite,
                             error_type=ExportError)
    out.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8", newline="\n")

    return workflow_manifest(
        "minecraft_pack",
        created_files=[file_entry("metadata", str(out), "mcmeta")],
        suggested_next_actions=[
            f"pack.mcmeta written with pack_format {resolved_format}"
            + (f" (from Minecraft {mc_version or mc.DEFAULT_MC_VERSION})"
               if pack_format is None else " (explicit)"),
            "Add textures with export_minecraft_texture(..., pack_root=...).",
            f"Drop '{pack_root}' into .minecraft/resourcepacks/ to test it in game.",
        ],
    )


@mcp.tool()
def write_texture_mcmeta(
    texture_path: str,
    frametime: int = 1,
    interpolate: bool = False,
    frame_order: list | None = None,
    frame_width: int | None = None,
    frame_height: int | None = None,
    overwrite: bool = False,
) -> dict:
    """Write the ``<texture>.png.mcmeta`` sidecar for an animated texture.

    ``export_minecraft_texture`` writes this automatically for a multi-frame sprite; use
    this to add or repair one beside a PNG that already exists.

    Args:
        texture_path: Path to the ``.png`` (the sidecar goes beside it, same name + .mcmeta).
        frametime: Ticks each frame is shown for (1 tick = 50 ms).
        interpolate: Blend between frames — smooth for gradients, blurry for pixel art.
        frame_order: Optional playback order: frame indices (0-based) or
            ``{"index": i, "time": t}`` objects to hold individual frames longer.
        frame_width, frame_height: Only for non-square frames, which the game otherwise
            infers from the strip's width.

    Returns a ``workflow_manifest.v1`` manifest (kind ``minecraft_texture``).
    """
    if not str(texture_path).endswith(".png"):
        raise ExportError(
            f"texture_path should be the .png itself (got {texture_path!r}); the sidecar is "
            "named <texture>.png.mcmeta."
        )
    document = mc.animation_mcmeta(frametime, interpolate, frame_order,
                                   frame_width, frame_height)
    out = ensure_output_path(f"{texture_path}.mcmeta", overwrite=overwrite,
                             error_type=ExportError)
    out.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8", newline="\n")
    return workflow_manifest(
        "minecraft_texture",
        created_files=[file_entry("metadata", str(out), "mcmeta")],
        suggested_next_actions=[
            (f"Sidecar written: {out.name}. The PNG must be a vertical strip of square "
             "frames for it to mean anything."),
        ],
    )


