"""The craft properties that separate placed pixel art from a rendered picture.

`quality` measures whether a drawing has form, `ramplint` measures whether its colour is
coherent, and `figure` measures whether its shapes hold together. None of them measures
whether the thing was *made as pixel art*, and that turned out to be the difference
between this project's output and the reference work it was being compared against.

Measured on four reference pieces supplied as a quality bar, three of them were not pixel
art at all: 85 to 96 percent of their colour clusters were single pixels and they carried
3,000 to 145,000 colours, because they are illustrations put through a pixel-style filter.
The fourth sat on a 4px grid and still ran 96 percent singletons. Chasing that density in
indexed art produces noise, and nothing in this module's siblings could say so.

So this module answers four questions that the others cannot:

* **Is the colour placed or painted?** `clusters` reports the size distribution of
  single-colour regions. Placed pixel art builds areas; a filtered photograph builds
  speckle.
* **Is the silhouette drawn or ruled?** `edge_runs` reports the run lengths down the
  drawing's outer edges. A drawn curve varies them; a shape generated by interpolating
  between two endpoints repeats one.
* **Does the picture have a value structure?** `value_split` reports how luminance
  distributes. A figure on transparency has no structure at all, which is why it reads as
  an asset rather than as a picture.
* **Is the darkest thing the keyline?** `keyline_integrity` answers it, because three
  separate ramps in one session bottomed out at pure black and silently beat the outline
  they were drawn beside.

Every function here measures and reports. Thresholds live in `readings`, are stated with
their provenance, and are kept deliberately few: the corpus that would earn more of them
does not exist yet, and a threshold without one is an opinion wearing a number.
"""

from __future__ import annotations

